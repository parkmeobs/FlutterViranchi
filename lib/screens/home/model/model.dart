class HeaderItem {
  final int id;
  final String label;
  final String image;
  final double width;
  final double height;
  final String screen;
  final bool navigate;

  HeaderItem({
    required this.id,
    required this.label,
    required this.image,
    required this.width,
    required this.height,
    required this.screen,
    required this.navigate,
  });
}